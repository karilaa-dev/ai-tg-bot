/** Dates and times follow the interface language, in the visitor's regional variant. */
export function chatFormat(language: UiLanguage) {
  const locale = localeFor(language);
  const time = new Intl.DateTimeFormat(locale, { hour: "numeric", minute: "2-digit" });
  const weekday = new Intl.DateTimeFormat(locale, { weekday: "short" });
  const monthDay = new Intl.DateTimeFormat(locale, { month: "short", day: "numeric" });
  const shortDate = new Intl.DateTimeFormat(locale, { dateStyle: "short" });
  const full = new Intl.DateTimeFormat(locale, { dateStyle: "full", timeStyle: "short" });
  const longDay = new Intl.DateTimeFormat(locale, { weekday: "long", month: "long", day: "numeric" });
  const longDayYear = new Intl.DateTimeFormat(locale, { weekday: "long", month: "long", day: "numeric", year: "numeric" });
  const month = new Intl.DateTimeFormat(locale, { month: "long" });
  return {
    time: (value: number) => time.format(value),
    full: (value: number) => full.format(value),
    /** Telegram-style list date: time for recent days, weekday this week, then the date. */
    listDate: (value: number, now = Date.now()) => {
      const date = new Date(value);
      const today = new Date(now);
      const startOfToday = new Date(today.getFullYear(), today.getMonth(), today.getDate()).getTime();
      const startOfYesterday = new Date(today.getFullYear(), today.getMonth(), today.getDate() - 1).getTime();
      const startOfWeek = new Date(today.getFullYear(), today.getMonth(), today.getDate() - 6).getTime();
      if (value >= startOfYesterday) return time.format(value);
      if (value >= startOfWeek && value < startOfToday) return capitalize(weekday.format(value));
      return date.getFullYear() === today.getFullYear() ? monthDay.format(value) : shortDate.format(value);
    },
    day: (value: number, now = Date.now()) => capitalize((new Date(value).getFullYear() === new Date(now).getFullYear() ? longDay : longDayYear).format(value)),
    month: (year: number, monthIndex: number, currentYear: number) => {
      const name = capitalize(month.format(new Date(year, monthIndex, 1)));
      return year === currentYear ? name : `${name} ${year}`;
    },
  };
}

